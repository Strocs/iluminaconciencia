/**
 * Per-viewport-aspect cover crop for the "window D" night-sky region.
 *
 * Pure, deterministic, side-effect free (no DOM, no GL, no I/O).
 *
 * The crop is a gap-aware maximum inscribed rectangle (MIR) derived offline
 * from the real BSC5 window D catalog (5,530 stars) with the same
 * stereographic projection as star-mapper.ts (tangent RA 9.75h, Dec -7.5 deg,
 * y-up). The window D region is NOT convex in projection: the Dec +70
 * parallel dips to y = 1.605 at the tangent column, so above that height the
 * region splits into two prongs with an empty gap in the center. The MIR
 * therefore pins its top at that dip (TOP_CAP) and its bottom at the
 * southernmost marquee star (Rigil Kent, y = -1.357, minus a 0.1 pad), then
 * maximizes the star count over the feasible x positions. The result is a
 * lookup table of projected rects per aspect (1.00..2.50, step 0.05); the
 * runtime interpolates between entries and falls back to a marquee-centered
 * full-width rect beyond 2.50 (the hard geometric limit where all 24 marquee
 * can no longer fit is aspect ~2.64).
 *
 * Portrait (aspect < 1) keeps the group-centered column decided earlier:
 * full-height, centered on Sirius/Canopus/Acrux/Regulus.
 *
 * All constants below are projected stereographic units, y-UP. The exported
 * `computeSkyCrop` returns cover uniforms in normalized 0..1 space with y = 0
 * at the TOP (matches the star-mapper/shader convention).
 */

/** Projected region bounding box of the window D catalog (y-up). */
const REGION = { xMin: -3.2244, xMax: 3.7127, yMin: -2.1081, yMax: 2.6389 } as const
/** Projected bbox of the 24 marquee stars (landscape guarantee set). */
const MARQUEE = { xMin: -1.5954, xMax: 1.3308, yMin: -1.3565, yMax: 1.2747 } as const
/** Projected bbox of the portrait group (Sirius/Canopus/Acrux/Regulus). */
const GROUP = { xMin: -0.7921, xMax: 0.4022, gcx: -0.2283 } as const

/**
 * Cover-crop uniforms in normalized 0..1 space, y = 0 at the TOP. Applied in
 * the star vertex shader as `(a_origin * u_cropScale - u_cropOffset)`, so the
 * region's own 0..1 space is scaled about the origin then translated to cover
 * the full viewport.
 */
export interface SkyCrop {
  readonly scaleX: number
  readonly scaleY: number
  readonly offsetX: number
  readonly offsetY: number
}

/**
 * Projected region bounding box of the window D catalog (y-up). Single source
 * of truth for the region bounds, imported by star-mapper.ts.
 */
