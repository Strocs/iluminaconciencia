/** Clamp a value to the inclusive `[low, high]` range; when the value lies
 * strictly outside the range, fall back to the midpoint instead of the nearest
 * endpoint (so a pathological aspect never pins the crop to a region edge).
 */
const clampMid = (value: number, low: number, high: number): number =>
  low <= value && value <= high ? value : (low + high) / 2

const clamp = (value: number, minimum: number, maximum: number): number => Math.min(maximum, Math.max(minimum, value))

const lerp = (from: number, to: number, fraction: number): number => from + (to - from) * fraction

/**
 * Compute the cover-crop uniforms for a given viewport aspect (width/height).
 *
 * @param aspect - viewport aspect ratio (width / height), must be finite and > 0.
 * @returns cover-crop uniforms in normalized 0..1 space, y = 0 at the TOP.
 */
export function computeSkyCrop(aspect: number): SkyCrop {
  if (!Number.isFinite(aspect) || aspect <= 0) {
    return { scaleX: 1, scaleY: 1, offsetX: 0, offsetY: 0 }
  }

  let x0: number
  let y0: number
  let w: number
  let h: number

  if (aspect < 1) {
    // Portrait: full-height column centered on the group (no envelope narrowing).
    h = REGION.yMax - REGION.yMin
    w = h * aspect
    x0 = clampMid(GROUP.gcx - w / 2, GROUP.xMax - w, GROUP.xMin)
    y0 = REGION.yMin
  } else if (aspect <= 2.0) {
    // Landscape: interpolate the gap-aware MIR lookup table.
    const position = (aspect - 1) / 0.05
    const index = clamp(Math.floor(position), 0, MIR_RECTS.length - 2)
    const fraction = position - index
    const from = MIR_RECTS[index]
    const to = MIR_RECTS[index + 1]
    h = lerp(from.h, to.h, fraction)
    y0 = lerp(from.y0, to.y0, fraction)
    x0 = lerp(from.x0, to.x0, fraction)
    w = aspect * h
  } else {
    // Ultra-wide: closed-form branch, full-width rect, y0 clamped ≥ HORIZON_Y.
    w = Math.min(REGION.xMax - REGION.xMin, aspect * (REGION.yMax - REGION.yMin))
    h = w / aspect
    y0 = (MARQUEE.yMin + MARQUEE.yMax - h) / 2
    // Clamp y0 so the bottom edge never drops below the horizon.
    if (y0 < HORIZON_Y) y0 = HORIZON_Y
    if (h < MARQUEE.yMax - MARQUEE.yMin) {
      y0 = clampMid((REGION.yMin + REGION.yMax - h) / 2, MARQUEE.yMax - h, MARQUEE.yMin)
      if (y0 < HORIZON_Y) y0 = HORIZON_Y
    }
    x0 = (REGION.xMin + REGION.xMax - w) / 2
  }

  // Convert the y-up rect to normalized y-down cover uniforms.
  const scaleX = (REGION.xMax - REGION.xMin) / w
  const scaleY = (REGION.yMax - REGION.yMin) / h
  const offsetX = ((x0 - REGION.xMin) / (REGION.xMax - REGION.xMin)) * scaleX
  const offsetY = (1 - ((y0 + h) - REGION.yMin) / (REGION.yMax - REGION.yMin)) * scaleY

  return { scaleX, scaleY, offsetX, offsetY }
}