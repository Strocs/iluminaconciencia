/**
 * Per-viewport-aspect cover crop for the south first-person night-sky region.
 *
 * Pure, deterministic, side-effect free (no DOM, no GL, no I/O).
 *
 * The crop is a gap-aware maximum inscribed rectangle (MIR) derived offline
 * from the BSC5 south catalog (3,369 stars) with the stereographic projection
 * as star-mapper.ts (tangent RA 9.75h, Dec −70°, y-up, mirrored x). The MIR is
 * computed over stars above the horizon (projected y ≥ −0.933), maximizes star
 * count per aspect, and is clamped to the region bbox.
 *
 * Portrait (aspect < 1) keeps the group-centered full-height column
 * (h ≈ 3.186, the full region span), centered on Canopus/Acrux/Rigil Kent/Hadar.
 *
 * Ultra-wide (aspect > 2.0) uses a closed-form branch: full-width rect with
 * y0 clamped ≥ HORIZON_Y (−0.933) so no star below the horizon is visible.
 *
 * All constants below are projected stereographic units, y-UP, mirrored x. The
 * exported `computeSkyCrop` returns cover uniforms in normalized 0..1 space with
 * y = 0 at the TOP (matches the star-mapper/shader convention).
 */

/** Horizon Y cap (projected units): stars below this are excluded from the viewport. */
const HORIZON_Y = -0.933
/** Projected region bounding box of the south catalog (mirrored x, y-up). */
const REGION = { xMin: -1.5916, xMax: 1.6023, yMin: -2.1536, yMax: 1.0328 } as const
/** Projected bbox of the marquee stars (landscape guarantee set, mirrored space). */
const MARQUEE = { xMin: -0.90, xMax: 0.98, yMin: -0.76, yMax: 0.79 } as const
/** Projected bbox of the portrait group (Canopus/Acrux/Rigil Kent/Hadar, mirrored space). */
const GROUP = { xMin: -0.50, xMax: 0.50, gcx: 0.04 } as const

/**
 * Cover-crop uniforms in normalized 0..1 space, y = 0 at the TOP. Applied in
 * the star vertex shader as `(a_origin * u_cropScale - u_cropOffset)`, so the
 * region's own 0..1 space is scaled about the origin then translated to cover
 * the full viewport.
 */
export interface SkyCrop {
  readonly scaleX: number
  readonly scaleY: number
  readonly offsetX: number
  readonly offsetY: number
}

/**
 * Projected region bounding box of the window D catalog (mirrored x, y-up). Single source
 * of truth for the region bounds, imported by star-mapper.ts.
 */
export const REGION_BBOX = REGION
/** Projected bbox of the 24 marquee stars (landscape guarantee set). */
export const MARQUEE_BBOX = MARQUEE
/** Projected bbox of the portrait group (Canopus/Acrux/Rigil Kent/Hadar). */
export const PORTRAIT_GROUP = GROUP

